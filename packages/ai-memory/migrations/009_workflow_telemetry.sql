-- Content-free, producer-attributed observations. No host content or payload bag.
CREATE TABLE ai_workflow_events (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  schema_version SMALLINT NOT NULL CHECK (schema_version = 1),
  kind TEXT NOT NULL CHECK (kind IN ('host','usage','edge','correlation')),
  producer VARCHAR(64) NOT NULL CHECK (producer ~ '^[A-Za-z0-9_.:-]+$'),
  event_id VARCHAR(128) NOT NULL CHECK (event_id ~ '^[A-Za-z0-9_.:-]+$'),
  source TEXT NOT NULL CHECK (source IN ('codex-hook','claude-hook','openai-responses','producer')),
  ingested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  observed_at TIMESTAMPTZ,
  project_id TEXT CHECK (project_id ~ '^sha256:[a-f0-9]{64}$'),
  task_id VARCHAR(128) CHECK (task_id ~ '^[A-Za-z0-9_.:-]+$'),
  session_id VARCHAR(128) CHECK (session_id ~ '^[A-Za-z0-9_.:-]+$'),
  turn_id VARCHAR(128) CHECK (turn_id ~ '^[A-Za-z0-9_.:-]+$'),
  response_id VARCHAR(128) CHECK (response_id ~ '^[A-Za-z0-9_.:-]+$'),
  host TEXT CHECK (host IN ('codex','claude-code')),
  model VARCHAR(128) CHECK (model ~ '^[A-Za-z0-9_.:-]+$'),
  stage VARCHAR(64) CHECK (stage ~ '^[A-Za-z0-9_.:-]+$'),
  tool_category VARCHAR(64) CHECK (tool_category ~ '^[A-Za-z0-9_.:-]+$'),
  edge TEXT CHECK (edge IN ('stage','retry','failure','blocker','correction','accepted')),
  attempt BIGINT CHECK (attempt BETWEEN 1 AND 9007199254740991),
  execution_ms BIGINT CHECK (execution_ms BETWEEN 0 AND 9007199254740991),
  queue_ms BIGINT CHECK (queue_ms BETWEEN 0 AND 9007199254740991),
  related_producer VARCHAR(64) CHECK (related_producer ~ '^[A-Za-z0-9_.:-]+$'),
  related_event_id VARCHAR(128) CHECK (related_event_id ~ '^[A-Za-z0-9_.:-]+$'),
  evidence_ids TEXT[] NOT NULL DEFAULT '{}' CHECK (cardinality(evidence_ids) <= 8 AND array_position(evidence_ids, NULL) IS NULL AND (cardinality(evidence_ids) = 0 OR (array_ndims(evidence_ids) = 1 AND array_lower(evidence_ids, 1) = 1 AND array_to_string(evidence_ids, ',') ~ '^[A-Za-z0-9_.:-]{1,128}(,[A-Za-z0-9_.:-]{1,128}){0,7}$'))),
  host_event TEXT CHECK (host_event IN ('SessionStart','Stop','SessionEnd')),
  dedup_coverage TEXT NOT NULL CHECK (dedup_coverage IN ('producer-stable','host-turn','invocation-only')),
  usage_accounting TEXT CHECK (usage_accounting IN ('openai-responses','unknown')),
  input_tokens BIGINT CHECK (input_tokens BETWEEN 0 AND 9007199254740991),
  cached_input_tokens BIGINT CHECK (cached_input_tokens BETWEEN 0 AND 9007199254740991),
  cache_write_input_tokens BIGINT CHECK (cache_write_input_tokens BETWEEN 0 AND 9007199254740991),
  output_tokens BIGINT CHECK (output_tokens BETWEEN 0 AND 9007199254740991),
  reasoning_output_tokens BIGINT CHECK (reasoning_output_tokens BETWEEN 0 AND 9007199254740991),
  payload_fingerprint TEXT NOT NULL CHECK (payload_fingerprint ~ '^[a-f0-9]{64}$'),
  UNIQUE (producer, event_id),
  CHECK (cached_input_tokens <= input_tokens),
  CHECK (cache_write_input_tokens <= input_tokens),
  CHECK (cached_input_tokens::numeric + cache_write_input_tokens::numeric <= input_tokens),
  CHECK (cached_input_tokens::numeric + cache_write_input_tokens::numeric <= 9007199254740991),
  CHECK (input_tokens::numeric + output_tokens::numeric <= 9007199254740991),
  CHECK (reasoning_output_tokens <= output_tokens),
  CHECK ((related_producer IS NULL) = (related_event_id IS NULL)),
  CHECK (kind <> 'usage' OR (source = 'openai-responses' AND response_id IS NOT NULL AND edge IS NULL AND host_event IS NULL AND related_producer IS NULL)),
  CHECK (kind <> 'host' OR (host_event IS NOT NULL AND host IS NOT NULL AND edge IS NULL AND related_producer IS NULL AND usage_accounting IS NULL AND source = CASE host WHEN 'codex' THEN 'codex-hook' ELSE 'claude-hook' END)),
  CHECK (kind NOT IN ('edge','correlation') OR (source = 'producer' AND project_id IS NOT NULL AND task_id IS NOT NULL AND cardinality(evidence_ids) > 0 AND host_event IS NULL AND usage_accounting IS NULL)),
  CHECK (kind <> 'edge' OR (stage IS NOT NULL AND edge IS NOT NULL AND (edge IN ('correction','accepted')) = (related_producer IS NOT NULL))),
  CHECK (kind <> 'correlation' OR (host IS NOT NULL AND session_id IS NOT NULL AND edge IS NULL AND related_producer IS NULL)),
  CHECK (dedup_coverage <> 'host-turn' OR (kind = 'host' AND host = 'codex' AND host_event = 'Stop' AND session_id IS NOT NULL AND turn_id IS NOT NULL)),
  CHECK ((kind = 'usage' AND usage_accounting IS NOT NULL) OR (input_tokens IS NULL AND cached_input_tokens IS NULL AND cache_write_input_tokens IS NULL AND output_tokens IS NULL AND reasoning_output_tokens IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ai_workflow_events_usage_response_idx ON ai_workflow_events(source, response_id) WHERE kind = 'usage';
CREATE INDEX IF NOT EXISTS ai_workflow_events_task_time_idx ON ai_workflow_events(project_id, task_id, ingested_at, id);
CREATE INDEX IF NOT EXISTS ai_workflow_events_host_session_idx ON ai_workflow_events(host, session_id, ingested_at, id);
CREATE INDEX IF NOT EXISTS ai_workflow_events_retention_ingested_idx ON ai_workflow_events(ingested_at, id);
