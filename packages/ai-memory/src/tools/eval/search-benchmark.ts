#!/usr/bin/env node

/**
 * Search latency benchmark for ai-memory.
 *
 * Seeds a deterministic synthetic corpus into an empty, disposable database,
 * times `searchMemories` for many-term, long and issue-reference queries, and
 * reports p50/p95/max per query class before removing the corpus. Word
 * frequencies are skewed so token-OR membership matches a large share of the
 * corpus, as agent queries do in practice. It refuses to run against a
 * database that already holds other memories.
 *
 * `--explain` also plans one query per class with the default planner settings
 * and reports the indexes it reads and any sequential scan of the memory table.
 *
 * Run via `npm run search:benchmark -w @aviaratech/ai-memory -- [--rows <n>] [--json] [--explain]`.
 */

import type { DbPool } from '@aviaratech/ai-memory/internal';

import { performance } from 'node:perf_hooks';
import { resolve } from 'node:path';

export const BENCHMARK_PROJECT = '__search_benchmark__';
const DEFAULT_ROWS = 40_000;
const SEED_BATCH_ROWS = 500;
const VOCABULARY_SIZE = 4_000;
// Larger skew concentrates draws on early vocabulary entries (Zipf-like).
const WORD_SKEW = 2.5;
const TIMED_RUNS = 3;
const SYLLABLES = ['ka', 'lo', 'mi', 'ne', 'ru', 'sa', 'ti', 'vo', 'ze', 'pa', 'do', 'fi', 'gu', 'he', 'ja', 'ko'];

export interface SeedSyntheticSearchCorpusInput {
  embeddings: boolean;
  project: string;
  rows: number;
  /** Deterministic seed in [-1, 1] for PostgreSQL `setseed`. */
  seed: number;
  /** Vocabulary entry included in every row, for tests that need a known match count. */
  sharedTerm?: string | undefined;
}

export type BenchmarkQueryClass = 'long' | 'many-term' | 'reference';

export interface BenchmarkQuery {
  queryClass: BenchmarkQueryClass;
  text: string;
}

interface ClassSummary {
  maxMs: number;
  medianMatchedRows: number;
  p50Ms: number;
  p95Ms: number;
  queries: number;
  runs: number;
}

interface PlanSummary {
  /** Most rows any one scan of the memory table read and then discarded with a filter or recheck. */
  discardedRows: number;
  indexes: string[];
  /** Sequential scans of the memory table in the candidate-retrieval statement. */
  tableScans: number;
}

export interface SearchBenchmarkReport {
  byClass: Record<BenchmarkQueryClass, ClassSummary>;
  embeddings: boolean;
  measuredAt: string;
  plans?: Record<BenchmarkQueryClass, PlanSummary>;
  rows: number;
}

/** Deterministic pseudo-words that the English text-search configuration keeps as distinct lexemes. */
export function buildBenchmarkVocabulary(size = VOCABULARY_SIZE): string[] {
  const words: string[] = [];
  for (let index = 0; words.length < size; index += 1) {
    let value = index;
    let word = '';
    do {
      word += SYLLABLES[value % SYLLABLES.length] ?? '';
      value = Math.floor(value / SYLLABLES.length);
    } while (value > 0);
    words.push(`${word}x`);
  }
  return words;
}

/** Inserts synthetic rows directly; the stored search vector is generated by PostgreSQL. */
export async function seedSyntheticSearchCorpus(pool: DbPool, input: SeedSyntheticSearchCorpusInput): Promise<void> {
  const vocabulary = buildBenchmarkVocabulary();
  const client = await pool.connect();
  try {
    await client.query('SELECT setseed($1)', [input.seed]);
    for (let start = 0; start < input.rows; start += SEED_BATCH_ROWS) {
      const end = Math.min(input.rows, start + SEED_BATCH_ROWS);
      const embeddingColumn = input.embeddings ? ', embedding' : '';
      const embeddingValue = input.embeddings
        ? // Clustered like real embeddings; uniformly random vectors make HNSW inserts pathologically slow.
          `, CASE WHEN g % 2 = 0 THEN (
              SELECT array_agg(CASE WHEN dimension % 32 = g % 32 THEN 1 ELSE random() / 100 END::real ORDER BY dimension)
              FROM generate_series(1, 1536) AS dimension WHERE g > 0
            )::vector END`
        : '';
      await client.query(
        `INSERT INTO ai_memory_entries (
           content, project, category, memory_type, tags, source, confidence, evidence_refs, expires_at${embeddingColumn}
         )
         SELECT
           concat_ws(' ', NULLIF($3::text, ''),
             array_to_string(ARRAY(
               SELECT ($4::text[])[1 + floor(power(random(), $5::float8) * cardinality($4::text[]))::int]
               FROM generate_series(1, 15 + (g % 95))
             ), ' '),
             CASE WHEN g % 10 < 3 THEN 'issue #' || (1 + floor(random() * 5000)::int)::text END),
           $6::text,
           (ARRAY['decision','decision','decision','root-cause','architecture','convention','reflective','session-summary'])[1 + g % 8],
           (ARRAY['semantic','semantic','semantic','episodic','semantic','procedural','reflective','episodic'])[1 + g % 8],
           ARRAY[($4::text[])[1 + (g * 7) % cardinality($4::text[])], ($4::text[])[1 + (g * 13) % cardinality($4::text[])]],
           'synthetic-benchmark',
           0.5 + (g % 5) / 10.0,
           CASE WHEN g % 2 = 0 THEN jsonb_build_array('https://example.invalid/issues/' || (g % 5000)::text) ELSE '[]'::jsonb END,
           CASE WHEN g % 8 = 7 THEN NOW() + INTERVAL '30 days' END
           ${embeddingValue}
         FROM generate_series($1::int, $2::int) AS g`,
        [start + 1, end, input.sharedTerm ?? '', vocabulary, WORD_SKEW, input.project],
      );
    }
  } finally {
    client.release();
  }
}

/** Deletes a seeded corpus in batches so each statement stays inside the write budget. */
export async function removeSyntheticSearchCorpus(pool: DbPool, project: string): Promise<void> {
  let deleted: number;
  do {
    const result = await pool.query(
      `DELETE FROM ai_memory_entries
       WHERE id IN (SELECT id FROM ai_memory_entries WHERE project = $1 LIMIT $2)`,
      [project, SEED_BATCH_ROWS],
    );
    deleted = result.rowCount ?? 0;
  } while (deleted > 0);
}

/** Deterministic query set drawn from the corpus vocabulary with the same skew. */
export function buildBenchmarkQueries(): BenchmarkQuery[] {
  const vocabulary = buildBenchmarkVocabulary();
  let state = 0x5eed;
  const random = () => {
    state = (state + 0x6d2b79f5) | 0;
    let value = Math.imul(state ^ (state >>> 15), 1 | state);
    value = (value + Math.imul(value ^ (value >>> 7), 61 | value)) ^ value;
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
  const words = (count: number) =>
    Array.from(
      { length: count },
      () => vocabulary[Math.floor(Math.pow(random(), WORD_SKEW) * vocabulary.length)] ?? '',
    ).join(' ');
  return [
    ...Array.from({ length: 20 }, () => ({ queryClass: 'many-term' as const, text: words(14) })),
    ...Array.from({ length: 5 }, () => ({ queryClass: 'long' as const, text: words(50) })),
    ...Array.from({ length: 5 }, () => ({
      queryClass: 'reference' as const,
      text: `issue #${String(1 + Math.floor(random() * 5000))} ${words(6)}`,
    })),
  ];
}

export type LabelledFrequency = 'common' | 'frequent' | 'medium' | 'rare';

export interface LabelledQuery {
  /** How common the query's terms are in the synthetic corpus. */
  frequency: LabelledFrequency;
  query: string;
  /** Contents of the planted records that answer the query; plant them before searching. */
  relevantContents: string[];
}

const LABELLED_QUERIES_PER_BAND = 8;
const LABELLED_BANDS: Record<LabelledFrequency, [number, number]> = {
  // Indexes into the benchmark vocabulary, whose use is skewed toward the first entries.
  common: [0, 12],
  frequent: [12, 60],
  medium: [150, 450],
  rare: [3000, 3999],
};

/**
 * Deterministic labelled queries for ranking at scale. Each query is five terms drawn from one frequency
 * band, and two planted records answer it by containing those terms in a short sentence. Planted records
 * should be old, so recency alone cannot find them. Rare and medium bands need only the index; the common
 * band, where thousands of rows contain every term, is where ranking by density matters.
 */
export function buildLabelledQueries(): LabelledQuery[] {
  const vocabulary = buildBenchmarkVocabulary();
  let state = 0x1abe1;
  const random = () => {
    state = (state + 0x6d2b79f5) | 0;
    let value = Math.imul(state ^ (state >>> 15), 1 | state);
    value = (value + Math.imul(value ^ (value >>> 7), 61 | value)) ^ value;
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
  const queries: LabelledQuery[] = [];
  for (const frequency of ['rare', 'medium', 'frequent', 'common'] as const) {
    const [low, high] = LABELLED_BANDS[frequency];
    for (let index = 0; index < LABELLED_QUERIES_PER_BAND; index += 1) {
      const terms = new Set<string>();
      while (terms.size < 5) terms.add(vocabulary[low + Math.floor(random() * (high - low))] ?? '');
      const words = [...terms];
      queries.push({
        frequency,
        query: words.join(' '),
        relevantContents: [
          `Decision record: ${words.join(' ')} were reviewed together.`,
          `Follow-up note on ${words.slice(0, 3).join(' ')} and ${words.slice(3).join(' ')} in one review.`,
        ],
      });
    }
  }
  return queries;
}

/** Mirrors search's token-OR membership for reporting how many rows a query reaches. */
function toTokenOrQuery(text: string): string {
  return text
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(token => token.length > 0)
    .join(' OR ');
}

function percentile(values: number[], fraction: number): number {
  const sorted = [...values].sort((left, right) => left - right);
  const index = Math.min(sorted.length - 1, Math.max(0, Math.ceil(fraction * sorted.length) - 1));
  return sorted[index] ?? 0;
}

function round(value: number): number {
  return Math.round(value * 10) / 10;
}

interface PlanNode {
  'Actual Loops'?: number;
  'Index Name'?: string;
  'Node Type': string;
  Plans?: PlanNode[];
  'Relation Name'?: string;
  'Rows Removed by Filter'?: number;
  'Rows Removed by Index Recheck'?: number;
}

function collectPlanNodes(node: PlanNode): PlanNode[] {
  return [node, ...(node.Plans ?? []).flatMap(collectPlanNodes)];
}

async function summarizePlan(pool: DbPool, sql: string, params: readonly unknown[]): Promise<PlanSummary> {
  // ANALYZE runs the statement: an index-order walk shows up as discarded rows, not as a scan type.
  const result = await pool.query<{ 'QUERY PLAN': { Plan: PlanNode }[] }>(`EXPLAIN (ANALYZE, FORMAT JSON) ${sql}`, [
    ...params,
  ]);
  const root = result.rows[0]?.['QUERY PLAN'][0]?.Plan;
  if (root === undefined) throw new Error('EXPLAIN returned no plan');
  const nodes = collectPlanNodes(root);
  const discarded = (node: PlanNode) =>
    (node['Actual Loops'] ?? 1) *
    ((node['Rows Removed by Filter'] ?? 0) + (node['Rows Removed by Index Recheck'] ?? 0));
  return {
    discardedRows: Math.max(0, ...nodes.filter(node => node['Relation Name'] === 'ai_memory_entries').map(discarded)),
    indexes: [...new Set(nodes.flatMap(node => (node['Index Name'] === undefined ? [] : [node['Index Name']])))].sort(),
    tableScans: nodes.filter(node => node['Node Type'] === 'Seq Scan' && node['Relation Name'] === 'ai_memory_entries')
      .length,
  };
}

function parseArgs(argv: string[]): { embeddings: boolean; explain: boolean; json: boolean; rows: number } {
  const args = { embeddings: true, explain: false, json: false, rows: DEFAULT_ROWS };
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === '--json') {
      args.json = true;
    } else if (value === '--explain') {
      args.explain = true;
    } else if (value === '--no-embeddings') {
      args.embeddings = false;
    } else if (value === '--rows') {
      const rows = Number(argv[index + 1]);
      if (!Number.isInteger(rows) || rows < 1) throw new Error('--rows must be a positive integer');
      args.rows = rows;
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${String(value)}`);
    }
  }
  return args;
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  const {
    assertLocalDatabaseUrl,
    buildHybridSearchQuery,
    closePool,
    getCapabilities,
    initializeDatabase,
    pool,
    searchMemories,
  } = await import('@aviaratech/ai-memory/internal');
  const databaseUrl = process.env.AI_MEMORY_DATABASE_URL;
  if (databaseUrl === undefined) throw new Error('AI_MEMORY_DATABASE_URL must name a disposable local database');
  assertLocalDatabaseUrl(databaseUrl);
  await initializeDatabase();

  const existing = await pool.query<{ count: string }>(
    'SELECT count(*)::text AS count FROM ai_memory_entries WHERE project IS DISTINCT FROM $1',
    [BENCHMARK_PROJECT],
  );
  if (existing.rows[0]?.count !== '0') {
    throw new Error('refusing to seed a database that holds other memories; use an empty disposable database');
  }

  const embeddings = args.embeddings && getCapabilities().hasEmbeddingColumn;
  try {
    await removeSyntheticSearchCorpus(pool, BENCHMARK_PROJECT);
    process.stderr.write(`Seeding ${String(args.rows)} synthetic memories...\n`);
    await seedSyntheticSearchCorpus(pool, { embeddings, project: BENCHMARK_PROJECT, rows: args.rows, seed: 0.42 });
    // Vacuum as autovacuum would: a bulk load leaves unset hint bits and pending index entries behind.
    await pool.query('VACUUM (ANALYZE) ai_memory_entries');

    const samples = new Map<BenchmarkQueryClass, { matched: number[]; timings: number[] }>();
    const plans: Partial<Record<BenchmarkQueryClass, PlanSummary>> = {};
    for (const query of buildBenchmarkQueries()) {
      if (args.explain && plans[query.queryClass] === undefined) {
        const statement = buildHybridSearchQuery({
          includeInactive: false,
          limit: 8,
          project: BENCHMARK_PROJECT,
          queryEmbedding: null,
          queryText: query.text,
        });
        plans[query.queryClass] = await summarizePlan(pool, statement.sql, statement.params);
      }
      const matched = await pool.query<{ count: string }>(
        `SELECT count(*)::text AS count FROM ai_memory_entries
         WHERE project = $3 AND search_vector @@ (websearch_to_tsquery('english', $1) || websearch_to_tsquery('english', $2))`,
        [query.text, toTokenOrQuery(query.text), BENCHMARK_PROJECT],
      );
      const sample = samples.get(query.queryClass) ?? { matched: [], timings: [] };
      sample.matched.push(Number(matched.rows[0]?.count ?? 0));
      await searchMemories({ includeEmbedding: false, project: BENCHMARK_PROJECT, query: query.text });
      for (let run = 0; run < TIMED_RUNS; run += 1) {
        const started = performance.now();
        await searchMemories({ includeEmbedding: false, project: BENCHMARK_PROJECT, query: query.text });
        sample.timings.push(performance.now() - started);
      }
      samples.set(query.queryClass, sample);
    }

    const byClass = Object.fromEntries(
      [...samples].map(([queryClass, sample]) => [
        queryClass,
        {
          maxMs: round(Math.max(...sample.timings)),
          medianMatchedRows: percentile(sample.matched, 0.5),
          p50Ms: round(percentile(sample.timings, 0.5)),
          p95Ms: round(percentile(sample.timings, 0.95)),
          queries: sample.matched.length,
          runs: sample.timings.length,
        },
      ]),
    ) as Record<BenchmarkQueryClass, ClassSummary>;
    const report: SearchBenchmarkReport = {
      byClass,
      embeddings,
      measuredAt: new Date().toISOString(),
      ...(args.explain ? { plans: plans as Record<BenchmarkQueryClass, PlanSummary> } : {}),
      rows: args.rows,
    };

    if (args.json) {
      process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
    } else {
      process.stdout.write(`searchMemories latency over ${String(report.rows)} synthetic memories\n`);
      for (const [queryClass, summary] of Object.entries(report.byClass)) {
        process.stdout.write(
          `  ${queryClass.padEnd(10)} queries=${String(summary.queries)} runs=${String(summary.runs)} ` +
            `matched(p50)=${String(summary.medianMatchedRows)} p50=${String(summary.p50Ms)}ms ` +
            `p95=${String(summary.p95Ms)}ms max=${String(summary.maxMs)}ms\n`,
        );
        const plan = report.plans?.[queryClass as BenchmarkQueryClass];
        if (plan !== undefined) {
          process.stdout.write(
            `  ${''.padEnd(10)} plan: table scans=${String(plan.tableScans)} discarded rows=${String(plan.discardedRows)} indexes=${plan.indexes.join(', ')}\n`,
          );
        }
      }
    }
  } finally {
    await removeSyntheticSearchCorpus(pool, BENCHMARK_PROJECT);
    await closePool();
  }
}

const scriptArg = process.argv[1] ?? '';
const isDirectRun =
  scriptArg.length > 0 && resolve(scriptArg).includes('search-benchmark') && !resolve(scriptArg).includes('.test.');

if (isDirectRun) {
  main().catch((error: unknown) => {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`[search-benchmark] ${message}\n`);
    process.exit(1);
  });
}
